export const ImportedRulesSchema = z.strictObject({
  source: z.strictObject({
    file: str,
    edition: z.enum(['vanilla', 'ptw', 'conquests']),
    version: str,
    title: str,
  }),
  buildings: z.array(BuildingSchema),
  citizens: z.array(CitizenSchema),
  cultureOpinions: z.array(CultureOpinionSchema),
  difficulties: z.array(DifficultySchema),
  eras: z.array(EraSchema),
  espionageMissions: z.array(EspionageMissionSchema),
  experienceLevels: z.array(ExperienceLevelSchema),
  resources: z.array(ResourceSchema),
  governments: z.array(GovernmentSchema),
  generalRules: GeneralRulesSchema,
  units: z.array(UnitSchema),
  civs: z.array(CivSchema),
  techs: z.array(TechSchema),
  workerJobs: z.array(WorkerJobSchema),
  terrains: z.array(TerrainSchema),
  worldSizes: z.array(WorldSizeSchema),
  flavors: z.array(FlavorSchema),
  game: GameSettingsSchema,
});

