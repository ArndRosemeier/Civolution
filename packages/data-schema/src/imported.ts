  bombardDefence: int,
  navalBombardDefence: int,
  defenceBonus: int,
  navalDefenceBonus: int,
  maintenanceCost: int,
  happyAll: int,
  happy: int,
  unhappyAll: int,
  unhappy: int,
  numReqBuildings: int,
  airPower: int,
  navalPower: int,
  pollution: int,
  production: int,
  reqGovernment: ref,
  spaceshipPart: ref,
  reqAdvance: ref,
  obsoleteBy: ref,
  reqResource1: ref,
  reqResource2: ref,
  improvementFlags: int,
  otherFlags: int,
