/**
 * Schema of the importer's output for the Conquests rule set
 * (data/imported/conquests.json). Field names are ours; values are the raw
 * numbers from the rule file. Index references (`ref`) point into the named
 * list and use -1 for "none".
 *
 * Unit notes worth knowing when curating:
 * - building `cost` and tech `cost` are stored in tens (Temple 6 = 60 shields);
 *   unit `shieldCost` is stored in full (Warrior 10).
 * - fields named unknownN are kept so nothing is lost; their meaning is not yet known.
 */
import { z } from 'zod';

const int = z.int();
const ref = z.int().min(-1);
const nonNeg = z.int().min(0);
const str = z.string();
const flags = z.array(z.string());

